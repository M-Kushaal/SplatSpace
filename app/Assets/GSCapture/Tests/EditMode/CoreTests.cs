    public class PoseConverterTests
    {
        struct Case
        {
            public Vector3 EyeGL, TargetGL;
            public float[] Expected; // row-major 4x4 c2w (OpenGL) from gs_pipeline (Python)

            public Case(Vector3 eye, Vector3 target, float[] expected)
            {
                EyeGL = eye;
                TargetGL = target;
                Expected = expected;
            }
        }

        // Generated by worker/tests/conftest.py:look_at_c2w_gl - the Python pipeline's own convention.
        static readonly Case[] Golden =
        {
            new Case(new Vector3(0.5f, 1.2f, 2.0f), new Vector3(0f, 0.3f, 0f), new float[] { 0.970143f, -0.097038f, 0.222277f, 0.500000f, 0.000000f, 0.916472f, 0.400099f, 1.200000f, -0.242536f, -0.388153f, 0.889108f, 2.000000f, 0.000000f, 0.000000f, 0.000000f, 1.000000f }),
            new Case(new Vector3(-1.5f, 0.4f, -0.7f), new Vector3(0.2f, 0.1f, 0.1f), new float[] { -0.425797f, 0.142669f, -0.893500f, -1.500000f, 0.000000f, 0.987491f, 0.157676f, 0.400000f, 0.904819f, 0.067138f, -0.420471f, -0.700000f, 0.000000f, 0.000000f, 0.000000f, 1.000000f }),
            new Case(new Vector3(0.3f, 2.0f, 0.1f), new Vector3(0f, 0f, 0f), new float[] { 0.316228f, -0.937043f, 0.148159f, 0.300000f, 0.000000f, 0.156174f, 0.987730f, 2.000000f, -0.948683f, -0.312348f, 0.049386f, 0.100000f, 0.000000f, 0.000000f, 0.000000f, 1.000000f }),
        };

        [Test]
        public void UnityLookAtMatchesPythonOpenGLLookAt()
        {
            foreach (var c in Golden)
            {
                // The same physical camera, expressed in Unity's left-handed world (z flipped).
                Vector3 eye = PoseConverter.ToOpenGLPoint(c.EyeGL), target = PoseConverter.ToOpenGLPoint(c.TargetGL);
                var rot = Quaternion.LookRotation(target - eye, Vector3.up);
                var m = PoseConverter.ToOpenGLCameraToWorld(eye, rot);
                for (int r = 0; r < 4; r++)
                for (int col = 0; col < 4; col++)
                    Assert.AreEqual(c.Expected[r * 4 + col], m[r, col], 1e-4f, $"eye {c.EyeGL} element [{r},{col}]");
            }
        }

        [Test]
        public void ConvertedCameraLooksDownNegativeZ()
        {
            var m = PoseConverter.ToOpenGLCameraToWorld(Vector3.zero, Quaternion.identity); // Unity: looking +z
            Vector3 forwardGL = -(Vector3)m.GetColumn(2);
            Assert.That(Vector3.Distance(forwardGL, new Vector3(0, 0, -1)), Is.LessThan(1e-6f));
            Assert.That(m.determinant, Is.EqualTo(1f).Within(1e-5f));
        }

        [Test]
        public void ImageRollRotatesAboutViewAxisOnly()
        {
            var m = PoseConverter.ToOpenGLCameraToWorld(new Vector3(1, 2, 3), Quaternion.Euler(10, 20, 30));
            var r = PoseConverter.ApplyImageRoll(m, 180);
            Assert.That(Vector3.Distance(m.GetColumn(2), r.GetColumn(2)), Is.LessThan(1e-5f));
            Assert.That(Vector3.Distance(m.GetColumn(0), -(Vector3)r.GetColumn(0)), Is.LessThan(1e-5f));
            Assert.AreEqual(m.GetColumn(3), r.GetColumn(3));
        }
    }

    public class ViewpointDomeTests
    {
        [Test]
        public void SlotsCoverAllRingsAndCameraAtSlotMatchesIt()
        {
            var dome = new ViewpointDome(Vector3.zero, 0.15f, 0.3f, 50f);
            Assert.AreEqual(24 + 24 + 16 + 4, dome.Slots.Count);
            Assert.That(dome.IdealDistance, Is.GreaterThan(0.25f));

            int i = 30;
            Vector3 pos = dome.SlotPosition(i);
            var m = dome.Evaluate(pos, (dome.Center - pos).normalized);
            Assert.AreEqual(i, m.SlotIndex);
            Assert.That(m.SlotAngleDeg, Is.LessThan(0.1f));
            Assert.That(m.DistanceRatio, Is.EqualTo(1f).Within(1e-4f));
            Assert.That(m.AimAngleDeg, Is.LessThan(0.1f));
        }

        [Test]
        public void FillingUpdatesCoverageAndSuggestion()
        {
            var dome = new ViewpointDome(Vector3.zero, 0.2f, 0.2f, 50f);
            Vector3 pos = dome.SlotPosition(5);
            Assert.AreEqual(5, dome.SuggestNext(pos));
            dome.MarkFilled(5);
            dome.MarkFilled(5);
            Assert.AreEqual(1, dome.FilledCount);
            Assert.AreNotEqual(5, dome.SuggestNext(pos));
            Assert.That(dome.Coverage, Is.EqualTo(1f / dome.Slots.Count).Within(1e-6f));
        }
    }

    public class CaptureGateTests
    {
        static GateInput Good() => new GateInput
        {
            Tracking = true, AimAngleDeg = 2, DistanceRatio = 1, SlotAngleDeg = 2, AngularSpeed = 0.03f,
            LinearSpeed = 0.02f, SteadySeconds = 1f, SharpnessRatio = 1.1f, Brightness = 130f,
        };

        [Test]
        public void GoodFramePasses()
        {
            Assert.AreEqual(GateReason.Ok, CaptureGate.Evaluate(Good(), GateConfig.Default));
        }

        [Test]
        public void EachProblemIsReported()
        {
            var c = GateConfig.Default;
            var i = Good(); i.Tracking = false;
            Assert.AreEqual(GateReason.NotTracking, CaptureGate.Evaluate(i, c));
            i = Good(); i.AimAngleDeg = 40;
            Assert.AreEqual(GateReason.NotAimed, CaptureGate.Evaluate(i, c));
            i = Good(); i.DistanceRatio = 0.3f;
            Assert.AreEqual(GateReason.TooClose, CaptureGate.Evaluate(i, c));
            i = Good(); i.DistanceRatio = 2.5f;
            Assert.AreEqual(GateReason.TooFar, CaptureGate.Evaluate(i, c));
            i = Good(); i.SlotAngleDeg = 15;
            Assert.AreEqual(GateReason.BetweenSlots, CaptureGate.Evaluate(i, c));
            i = Good(); i.SlotFilled = true;
            Assert.AreEqual(GateReason.AlreadyCaptured, CaptureGate.Evaluate(i, c));
            i = Good(); i.AngularSpeed = 0.2f; // the median speed of the first real capture: now rejected
            Assert.AreEqual(GateReason.MovingTooFast, CaptureGate.Evaluate(i, c));
            i = Good(); i.SteadySeconds = 0.1f;
            Assert.AreEqual(GateReason.Settling, CaptureGate.Evaluate(i, c));
            i = Good(); i.Brightness = 20f;
            Assert.AreEqual(GateReason.TooDark, CaptureGate.Evaluate(i, c));
            i = Good(); i.SharpnessRatio = 0.4f;
            Assert.AreEqual(GateReason.Blurry, CaptureGate.Evaluate(i, c));
            Assert.AreEqual(GateReason.Ok, CaptureGate.EvaluateGeometry(i, c)); // blur is not geometry
        }
    }

    public class BlurMeterTests
    {
        static NativeArray<byte> Checker(int w, int h, int cell, bool smooth)
        {
            var a = new NativeArray<byte>(w * h, Allocator.Temp);
            for (int y = 0; y < h; y++)
            for (int x = 0; x < w; x++)
            {
                float v = ((x / cell + y / cell) % 2 == 0) ? 1f : 0f;
                if (smooth) v = 0.5f + 0.5f * Mathf.Sin(x * 0.05f) * Mathf.Sin(y * 0.05f);
                a[y * w + x] = (byte)(v * 255);
            }
            return a;
        }

        [Test]
        public void SharpImageScoresHigherThanBlurryImage()
        {
            using (var sharp = Checker(320, 240, 3, false))
            using (var blurry = Checker(320, 240, 3, true))
            {
                double s = BlurMeter.Measure(sharp, 320, 240, 320).Sharpness;
                double b = BlurMeter.Measure(blurry, 320, 240, 320).Sharpness;
                Assert.That(s, Is.GreaterThan(b * 10));
            }
        }

        [Test]
        public void SensorNoiseDoesNotLookSharp()
        {
            // A smooth (blurry) image plus strong per-pixel noise, as in dim light, must still score far
            // below a genuinely sharp image: block averaging suppresses the noise.
            var rng = new System.Random(1);
            var sharp = Checker(320, 240, 12, false);
            var noisyBlur = Checker(320, 240, 12, true);
            try
            {
                for (int i = 0; i < noisyBlur.Length; i++)
                    noisyBlur[i] = (byte)Mathf.Clamp(noisyBlur[i] + rng.Next(-40, 41), 0, 255);
                double s = BlurMeter.Measure(sharp, 320, 240, 320).Sharpness;
                double n = BlurMeter.Measure(noisyBlur, 320, 240, 320).Sharpness;
                Assert.That(s, Is.GreaterThan(n * 5), $"sharp {s} vs noisy-blurry {n}");
            }
            finally
            {
                sharp.Dispose();
                noisyBlur.Dispose();
            }
        }

        [Test]
        public void BrightnessIsMeanLuminance()
        {
            var a = new NativeArray<byte>(64 * 64, Allocator.Temp);
            try
            {
                for (int i = 0; i < a.Length; i++) a[i] = 100;
                Assert.That(BlurMeter.Measure(a, 64, 64, 64).Brightness, Is.EqualTo(100f).Within(1e-3f));
            }
            finally
            {
                a.Dispose();
            }
        }

        [Test]
        public void TrackerRatioIsRelativeToMedian()
        {
            var t = new SharpnessTracker();
            Assert.AreEqual(1f, t.Ratio(5));
            for (int i = 0; i < 10; i++) t.Add(100);
            Assert.That(t.Ratio(50), Is.EqualTo(0.5f).Within(1e-6f));
        }
    }

    public class CaptureBundleWriterTests
    {
        /// <summary>
        /// Writes a full synthetic bundle (a camera at every dome slot) to app/Library/gscapture_sample_bundle.
        /// The Python validator is run on it as a cross-language check:
        ///   python -m gs_pipeline validate app/Library/gscapture_sample_bundle/manifest.json --no-files
        /// </summary>
        [Test]
        public void WritesManifestAndPlyTheValidatorCanRead()
        {
            var dome = new ViewpointDome(new Vector3(0.2f, 0f, 0.5f), 0.15f, 0.3f, 50f);
            var frames = new List<CapturedFrame>();
            for (int i = 0; i < dome.Slots.Count; i++)
            {
                Vector3 pos = dome.SlotPosition(i);
                var rot = Quaternion.LookRotation(dome.Center - pos, Vector3.up);
                frames.Add(new CapturedFrame
                {
                    FilePath = $"images/{i:D6}.jpg", CameraToWorldGL = PoseConverter.ToOpenGLCameraToWorld(pos, rot),
                    Fx = 1500, Fy = 1500, Cx = 960, Cy = 720, Width = 1920, Height = 1440, Timestamp = i * 0.5,
                    BlurScore = 120.5f, AngularVelocity = 0.05f, TargetId = i,
                });
            }
            var pts = new List<Vector3>();
            for (int i = 0; i < 500; i++)
                pts.Add(PoseConverter.ToOpenGLPoint(dome.Center + Random.insideUnitSphere * 0.15f));

            string dir = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "Library", "gscapture_sample_bundle"));
            Directory.CreateDirectory(dir);
            CaptureBundleWriter.WritePointsPly(Path.Combine(dir, "points3d.ply"), pts);
            var device = new Dictionary<string, string> { ["model"] = "editor \"test\"" };
            var stats = new Dictionary<string, int> { ["Ok"] = frames.Count, ["Blurry"] = 3 };
            string json = CaptureBundleWriter.ManifestJson("test_capture", "arcore", device, frames,
                PoseConverter.ToOpenGLPoint(dome.Center - Vector3.up * 0.15f), 0.15f, 0.3f, "points3d.ply", stats);
            File.WriteAllText(Path.Combine(dir, "manifest.json"), json);

            StringAssert.Contains("\"schema_version\": \"1.1\"", json);
            StringAssert.Contains("\"capture_mode\": \"object\"", json);
            StringAssert.Contains("\"object_bounds\"", json);
            StringAssert.Contains("\"model\": \"editor \\\"test\\\"\"", json);
            string ply = Path.Combine(dir, "points3d.ply");
            Assert.AreEqual(500 * 12, new FileInfo(ply).Length - HeaderLength(ply)); // 3 floats per point
        }

        static long HeaderLength(string path)
        {
            byte[] bytes = File.ReadAllBytes(path);
            string text = System.Text.Encoding.ASCII.GetString(bytes, 0, Mathf.Min(bytes.Length, 400));
            return text.IndexOf("end_header\n", System.StringComparison.Ordinal) + "end_header\n".Length;
        }
    }

    public class AnchoredFrameTests
    {
        [Test]
        public void LocalGeometryFollowsTheAnchor()
        {
            var f = new AnchoredFrame(new Vector3(1f, 0f, 2f));
            var cam = new Vector3(1.5f, 0.4f, 2f);
            Assert.That(Vector3.Distance(f.ToLocal(cam), new Vector3(0.5f, 0.4f, 0f)), Is.LessThan(1e-5f));

            // ARCore shifts its map by 4 cm: the same physical camera keeps the same local offset.
            var shift = new Vector3(0.04f, 0f, -0.02f);
            f.Update(new Vector3(1f, 0f, 2f) + shift, 0.033f);
            Assert.That(Vector3.Distance(f.ToLocal(cam + shift), new Vector3(0.5f, 0.4f, 0f)), Is.LessThan(1e-5f));
            Assert.That(Vector3.Distance(f.ToWorld(Vector3.zero), new Vector3(1f, 0f, 2f) + shift), Is.LessThan(1e-5f));
        }

        [Test]
        public void DisplayEasesTowardTheAnchor()
        {
            var f = new AnchoredFrame(Vector3.zero, 0.15f);
            var target = new Vector3(0.05f, 0f, 0f);
            f.Update(target, 0.033f);
            Assert.That(f.Display.x, Is.GreaterThan(0f).And.LessThan(0.05f)); // glides, no jump
            for (int i = 0; i < 60; i++) f.Update(target, 0.033f);           // ~2 s later it has arrived
            Assert.That(Vector3.Distance(f.Display, target), Is.LessThan(1e-4f));
            Assert.That(f.Origin, Is.EqualTo(target));                          // capture math never lags
        }
    }
